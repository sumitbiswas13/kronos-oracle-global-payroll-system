        REFERENCES GPS_PAYSLIPS (PAYSLIP_ID)
);

-- ── LEAVE TYPES ──────────────────────────────────────────────
CREATE TABLE GPS_LEAVE_TYPES (
    LEAVE_CODE          VARCHAR2(20)    NOT NULL,
    LEAVE_NAME          VARCHAR2(100)   NOT NULL,
    COUNTRY_CODE        VARCHAR2(3),                -- NULL = global
    DAYS_PER_YEAR       NUMBER(5,1)     DEFAULT 0,
    IS_PAID             CHAR(1)         DEFAULT 'Y' NOT NULL,
    CARRIES_OVER        CHAR(1)         DEFAULT 'N' NOT NULL,
    ACTIVE              CHAR(1)         DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_GPS_LEAVE_TYPES PRIMARY KEY (LEAVE_CODE)
);

-- ── LEAVE BALANCES ───────────────────────────────────────────
CREATE TABLE GPS_LEAVE_BALANCES (
    BALANCE_ID          NUMBER          GENERATED ALWAYS AS IDENTITY,
    EMPLOYEE_ID         NUMBER          NOT NULL,
    LEAVE_CODE          VARCHAR2(20)    NOT NULL,
    YEAR                NUMBER(4)       NOT NULL,
    ENTITLED_DAYS       NUMBER(5,1)     NOT NULL,
    TAKEN_DAYS          NUMBER(5,1)     DEFAULT 0 NOT NULL,
    PENDING_DAYS        NUMBER(5,1)     DEFAULT 0 NOT NULL,
    REMAINING_DAYS      NUMBER(5,1)     GENERATED ALWAYS AS (ENTITLED_DAYS - TAKEN_DAYS - PENDING_DAYS) VIRTUAL,
    CONSTRAINT PK_GPS_LEAVE_BALANCES PRIMARY KEY (BALANCE_ID),
    CONSTRAINT UK_GPS_LEAVE_BAL UNIQUE (EMPLOYEE_ID, LEAVE_CODE, YEAR),
    CONSTRAINT FK_GPS_LEAVE_BAL_EMP FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES GPS_EMPLOYEES (EMPLOYEE_ID),
    CONSTRAINT FK_GPS_LEAVE_BAL_TYPE FOREIGN KEY (LEAVE_CODE)
        REFERENCES GPS_LEAVE_TYPES (LEAVE_CODE)
);

-- ── LEAVE REQUESTS ───────────────────────────────────────────
CREATE TABLE GPS_LEAVE_REQUESTS (
    REQUEST_ID          NUMBER          GENERATED ALWAYS AS IDENTITY,
    EMPLOYEE_ID         NUMBER          NOT NULL,
    LEAVE_CODE          VARCHAR2(20)    NOT NULL,
    START_DATE          DATE            NOT NULL,
    END_DATE            DATE            NOT NULL,
    DAYS_REQUESTED      NUMBER(5,1)     NOT NULL,
    STATUS              VARCHAR2(20)    DEFAULT 'PENDING' NOT NULL, -- PENDING | APPROVED | REJECTED
    APPROVED_BY         NUMBER,
    NOTES               VARCHAR2(1000),
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_GPS_LEAVE_REQUESTS PRIMARY KEY (REQUEST_ID),
    CONSTRAINT FK_GPS_LR_EMP FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES GPS_EMPLOYEES (EMPLOYEE_ID),
    CONSTRAINT FK_GPS_LR_TYPE FOREIGN KEY (LEAVE_CODE)
        REFERENCES GPS_LEAVE_TYPES (LEAVE_CODE),
    CONSTRAINT FK_GPS_LR_MGR FOREIGN KEY (APPROVED_BY)
        REFERENCES GPS_EMPLOYEES (EMPLOYEE_ID)
);

-- ── AUDIT LOG ────────────────────────────────────────────────
CREATE TABLE GPS_AUDIT_LOG (
    LOG_ID              NUMBER          GENERATED ALWAYS AS IDENTITY,
    TABLE_NAME          VARCHAR2(100)   NOT NULL,
    RECORD_ID           VARCHAR2(50)    NOT NULL,
    ACTION              VARCHAR2(10)    NOT NULL,   -- INSERT | UPDATE | DELETE
    CHANGED_BY          VARCHAR2(100),
    CHANGED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    OLD_VALUES          CLOB,                       -- JSON snapshot
    NEW_VALUES          CLOB,                       -- JSON snapshot
    CONSTRAINT PK_GPS_AUDIT_LOG PRIMARY KEY (LOG_ID)
);

